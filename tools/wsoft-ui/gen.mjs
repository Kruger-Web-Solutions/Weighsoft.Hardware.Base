// Generates everything the firmware takes from the reference drawing (ref.js):
//   lib/wsoft_core/src/gen/wsoft_ui_fonts_1x.h   letters for the yellow board (320 x 240)
//   lib/wsoft_core/src/gen/wsoft_ui_fonts_2x.h   letters for the Waveshare (800 x 480)
//   lib/wsoft_core/src/gen/wsoft_ui_colors.h     the two colour sets and the status bar
//   lib/wsoft_core/src/gen/wsoft_ui_presets.h    the test screens (SCREEN SHOT n on the board)
//   test/test_wsoft_ui/golden.h                  the checksum each test screen must give
//   tools/wsoft-ui/fonts.json                    the same letters for the mock-up page
//   docs/img/wsoft-screen/*.png                  pictures of the test screens
// It runs gen.html in headless Edge or Chrome, because the letters are drawn by a browser's
// font engine (Manrope and Sora from Google Fonts, so it needs the internet).
//   node tools/wsoft-ui/gen.mjs
import { spawn } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createServer } from 'node:http';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildMockup } from './build.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const BROWSERS = [
  'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe',
  'C:\\Program Files\\Microsoft\\Edge\\Application\\msedge.exe',
  'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe',
  '/usr/bin/chromium', '/usr/bin/google-chrome',
];
const browser = process.env.WSOFT_UI_BROWSER || BROWSERS.find((p) => existsSync(p));
if (!browser) throw new Error('No Edge or Chrome found: set WSOFT_UI_BROWSER to its path');

const hex = (v, n) => '0x' + v.toString(16).toUpperCase().padStart(n, '0');
const cstr = (s) => '"' + String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"';
const lines = (items, per, indent = '    ') => {
  const rows = [];
  for (let i = 0; i < items.length; i += per) rows.push(indent + items.slice(i, i + per).join(',') + ',');
  return rows.join('\n');
};
const HEAD = '// Generated by tools/wsoft-ui/gen.mjs from tools/wsoft-ui/ref.js. Do not edit by hand.\n';

function fontsHeader(tag, roles, fonts) {
  let s = `${HEAD}// Letter shapes: Manrope and Sora, SIL Open Font License 1.1 (see docs/WSOFT-SCREEN.md).\n#pragma once\n\n#include "../wsoft_gfx.h"\n\n`;
  let total = 0;
  fonts.forEach((f, i) => {
    const name = `WSOFT_F${tag}_${roles[i]}`;
    total += f.bytes.length;
    s += `static const uint8_t ${name}_ALPHA[] = {\n${lines(f.bytes, 32)}\n};\n`;
    s += `static const WsoftGlyph ${name}_GLYPHS[] = {\n${lines(f.glyphs.map((g) => `{${g.join(',')}}`), 6)}\n};\n\n`;
  });
  s += `// In the order of WSOFT_UI_TINY ... WSOFT_UI_HERO. ${total} bytes of letter shapes.\n`;
  s += `static const WsoftFont WSOFT_UI_FONTS_${tag}[] = {\n`;
  fonts.forEach((f, i) => {
    const name = `WSOFT_F${tag}_${roles[i]}`;
    s += `    {${name}_GLYPHS, ${name}_ALPHA, ${f.first}, ${f.count}, ${f.cap}, ${f.track}},\n`;
  });
  return { text: s + '};\n', total };
}

function colorsHeader(theme, bar) {
  const keys = Object.keys(theme.dark), barKeys = Object.keys(bar);
  const row = (o, ks) => ks.map((k) => hex(o[k], 4)).join(', ');
  return `${HEAD}// Colours of the Edge bench screen, as 16-bit 5-6-5.\n#pragma once\n\n#include <stdint.h>\n\n` +
    `struct WsoftUiTheme {\n  uint16_t ${keys.join(', ')};\n};\n` +
    `struct WsoftUiBar {\n  uint16_t ${barKeys.join(', ')};\n};\n\n` +
    `static const WsoftUiTheme WSOFT_UI_DARK = {${row(theme.dark, keys)}};\n` +
    `static const WsoftUiTheme WSOFT_UI_LIGHT = {${row(theme.light, keys)}};\n` +
    `// The status bar is navy in both modes.\nstatic const WsoftUiBar WSOFT_UI_BAR = {${row(bar, barKeys)}};\n` +
    `static const uint16_t WSOFT_UI_WHITE = 0xFFFF;\nstatic const uint16_t WSOFT_UI_DARK_INK = 0x1946;\n`;
}

// Room for each text in WsoftUiModel (lib/wsoft_core/src/wsoft_ui_paint.h), the ending 0 included.
const ROOM = { ip: 16, hub: 14, link: 8, slot_title: 24, slot_detail: 36, reason: 18, steady: 10, plate: 64, audit: 18, label: 12,
  weight: 14, unit: 4, word: 14, product: 26, target: 26, low: 12, high: 12, gross: 22, save_line: 18, title: 12, message: 40,
  address: 20, ap_name: 34, caption: 14, value: 26 };
function checkRoom(title, key, text) {
  if (!(key in ROOM)) throw new Error('no room set for the text ' + key);
  if (text.length >= ROOM[key]) throw new Error(`test screen "${title}": ${key} is ${text.length} long, the model holds ${ROOM[key] - 1}`);
}

const TILE_ID = { approval: 'APPROVAL', auto: 'AUTO', tare: 'TARE', preset: 'PRESET', product: 'PRODUCT', theme: 'THEME', wifi: 'WIFI' };
function presetsHeader(models) {
  let s = `${HEAD}// The test screens: what test/test_wsoft_ui draws and what SCREEN SHOT n draws on a board.\n#pragma once\n\n` +
    `#include <string.h>\n\n#include "../wsoft_ui_paint.h"\n\n#define WSOFT_UI_PRESET_SET(field, text) strncpy(field, text, sizeof(field) - 1)\n\n` +
    `static const int WSOFT_UI_PRESET_COUNT = ${models.length};\n\n` +
    `// Fills *m with test screen n. False when there is no such screen.\ninline bool wsoft_ui_preset(int n, WsoftUiModel *m) {\n  memset(m, 0, sizeof *m);\n  switch (n) {\n`;
  models.forEach(({ title, model }, n) => {
    s += `    case ${n}:  // ${title}\n`;
    for (const [k, v] of Object.entries(model)) {
      if (k === 'tiles') {
        v.forEach((t, i) => {
          s += `      m->tiles[${i}].id = WSOFT_UI_TILE_${TILE_ID[t.id]};\n      m->tiles[${i}].look = ${t.look};\n`;
          checkRoom(title, 'caption', t.caption);
          checkRoom(title, 'value', t.value);
          s += `      WSOFT_UI_PRESET_SET(m->tiles[${i}].caption, ${cstr(t.caption)});\n      WSOFT_UI_PRESET_SET(m->tiles[${i}].value, ${cstr(t.value)});\n`;
        });
      } else if (typeof v === 'string') {
        checkRoom(title, k, v);
        if (v.length) s += `      WSOFT_UI_PRESET_SET(m->${k}, ${cstr(v)});\n`;
      } else if (v !== 0 && v !== false) {
        s += `      m->${k} = ${v};\n`;
      }
    }
    s += '      return true;\n';
  });
  return s + '  }\n  return false;\n}\n';
}

function goldenHeader(crc) {
  const row = (list) => list.map((v) => hex(v, 8)).join(', ');
  return `${HEAD}// CRC-32 of each test screen as the reference drawing gives it (low byte of each dot first).\n#pragma once\n\n#include <stdint.h>\n\n` +
    `static const uint32_t GOLDEN_1X[] = {${row(crc.yellow)}};\nstatic const uint32_t GOLDEN_2X[] = {${row(crc.wave)}};\n`;
}

function write(file, text) {
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, text);
  console.log('wrote', file.slice(root.length + 1), text.length, 'bytes');
}

function finish(data) {
  const one = fontsHeader('1X', data.roles, data.fonts.yellow), two = fontsHeader('2X', data.roles, data.fonts.wave);
  write(join(root, 'lib/wsoft_core/src/gen/wsoft_ui_fonts_1x.h'), one.text);
  write(join(root, 'lib/wsoft_core/src/gen/wsoft_ui_fonts_2x.h'), two.text);
  write(join(root, 'lib/wsoft_core/src/gen/wsoft_ui_colors.h'), colorsHeader(data.theme, data.bar));
  write(join(root, 'lib/wsoft_core/src/gen/wsoft_ui_presets.h'), presetsHeader(data.models));
  write(join(root, 'test/test_wsoft_ui/golden.h'), goldenHeader(data.crc));
  const b64 = (f) => ({ first: f.first, count: f.count, cap: f.cap, track: f.track, glyphs: f.glyphs, b64: Buffer.from(f.bytes).toString('base64') });
  write(join(here, 'fonts.json'), JSON.stringify({ yellow: data.fonts.yellow.map(b64), wave: data.fonts.wave.map(b64) }));
  for (const id of ['yellow', 'wave']) {
    data.png[id].forEach((url, n) => {
      const file = join(root, 'docs/img/wsoft-screen', `${id}-${String(n).padStart(2, '0')}.png`);
      mkdirSync(dirname(file), { recursive: true });
      writeFileSync(file, Buffer.from(url.split(',')[1], 'base64'));
    });
  }
  console.log(`pictures: docs/img/wsoft-screen (${data.png.yellow.length} screens x 2 boards)`);
  console.log(`letter shapes: yellow board ${one.total} bytes, Waveshare ${two.total} bytes`);
  console.log('mock-up:', buildMockup());
}

const TYPES = { '.html': 'text/html', '.js': 'text/javascript' };
const server = createServer((req, res) => {
  if (req.method === 'POST') {
    const chunks = [];
    req.on('data', (c) => chunks.push(c));
    req.on('end', () => {
      res.end('ok');
      const body = Buffer.concat(chunks).toString('utf8');
      let code = 0;
      try {
        if (req.url === '/done') finish(JSON.parse(body));
        else { console.error('generator failed in the browser:\n' + body); code = 1; }
      } catch (e) { console.error(e); code = 1; }
      child.kill();
      server.close(() => process.exit(code));
    });
    return;
  }
  const name = req.url === '/' ? 'gen.html' : req.url.slice(1).split('?')[0];
  const file = join(here, name);
  if (!/^[\w.-]+$/.test(name) || !existsSync(file)) { res.statusCode = 404; res.end(); return; }
  res.setHeader('Content-Type', TYPES[name.slice(name.lastIndexOf('.'))] || 'text/plain');
  res.end(readFileSync(file));
});
let child;
server.listen(0, '127.0.0.1', () => {
  const url = `http://127.0.0.1:${server.address().port}/gen.html`;
  child = spawn(browser, ['--headless=new', '--disable-gpu', `--user-data-dir=${join(here, 'out', 'edge-profile')}`, url], { stdio: 'ignore' });
  setTimeout(() => { console.error('timed out waiting for the browser'); child.kill(); process.exit(1); }, 120000).unref();
});
